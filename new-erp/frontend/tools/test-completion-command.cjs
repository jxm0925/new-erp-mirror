const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
;(async () => {
  const source = fs.readFileSync(path.join(__dirname, '../src/utils/completionCommand.js'), 'utf8')
  const { completionCommandStore, completionErrorIsDefinitive } = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'))
  const values = new Map()
  const storage = { getItem: key => values.get(key) || null, setItem: (key, value) => values.set(key, value), removeItem: key => values.delete(key) }
  let store = completionCommandStore(storage, 'review:1:42')
  const original = { id: 9, payload: { client_command_id: 'same-command', expected_version: 2, decision: 'approve', reason: null } }
  assert.deepEqual(store.prepare(original), original)
  store = completionCommandStore(storage, 'review:1:42')
  assert.deepEqual(store.prepare({ id: 9, payload: { client_command_id: 'new-command', decision: 'reject', reason: 'changed' } }), original)
  assert.throws(() => store.prepare({ id: 10, payload: original.payload }), /请先确认/)
  assert.equal(completionCommandStore(storage, 'review:2:42').read(), null)
  for (const status of [401, 403, 408, 429, 500, 502, 503]) assert.equal(completionErrorIsDefinitive({ response: { status } }), false)
  assert.equal(completionErrorIsDefinitive({}), false)
  assert.equal(completionErrorIsDefinitive({ response: { status: 409 }, errorCode: 'command_processing' }), false)
  assert.equal(completionErrorIsDefinitive({ response: { status: 409 }, errorCode: 'version_conflict' }), true)
  assert.equal(completionErrorIsDefinitive({ response: { status: 422 } }), true)
  store.clear(); assert.equal(store.read(), null)
  storage.setItem('review:1:42', '{}'); assert.throws(() => store.read(), /无法读取/)
  console.log('PASS: pending approval survives reload with original decision and version; actor isolation and uncertain-response boundaries verified.')
})().catch(error => { console.error(error); process.exitCode = 1 })
